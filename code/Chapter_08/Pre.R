金融市场和工具

市场是提供给每一个参与者实现交易的地点，它既是可以是一个实体的场地，也可以是一个虚拟的场地。在古希腊，雅典公民将聚集在agora，他们用蜂蜜，橄榄油，其它农产品，和艺术作品，来交易类似的商品。交易既能以实物进行或以货币进行。类似的交易市场存在遍布古代世界。这些实物市场，好比当今的现货市场，参与双方在交易前，必须就价钱和条目达成一致。

如今，世界上许多的实体交易市场正在慢慢被虚拟市场所占领覆盖，比较显著的几个例子是amazon.com，ebay.com和alibaba.com。买方和卖方在电脑前面交易和互动。


这些都是广大的网上市场买卖双方互动，完全通过电脑进行交易。类似的趋势已经在金融马歇尔凯茨已经发生在过去的几年中。期货，股票和期权交易所的老楼坑让位给电子平台。表1.1列出了近似的电子与在CME交易所场内交易量的百分比。 GLOBEX指芝加哥商业交易所（CME）的电子平台。



