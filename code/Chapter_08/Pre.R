1 概要
我写这本书的主要目的是为读者在工作和学业上提供可以成功应用的基础编程，金融，和数学工具。本书全部应用R编程语言和R环境，为维护金融市场数据和解决交易员和金融工程师在日常活动中所遇到的一系列问题提供解决方案。

接下来的章节可以视为推荐教程，其中的内容是我在多年做为金融工程师和交易员期间总结的非常有用的信息。这本书更偏向于金融工程师的应用角度，而不是说学术的角度。大部分的内容是基于我在芝加哥Loyola大学兼职期间的讲义。

这是一个入门级的书，针对于没有编程经验或高级数学知识的读者。话虽如此，如果读者以前有接触过类似相关的知识，有些章节读起来将会相对容易一些。在数学方面，我建议读者首先复习微积分，线性代数，统计数据和概率论的基本知识。在编程方面，熟悉VBA，Python中的审查，和SQL2是很有帮助的。

这本书也针对于那些想要对金融数据进行数据分析，和对工作流程进行R脚本进行学习的经验丰富的交易员和从业人员。

交易和编程是一个非常庞大的课题，我现在无论如何不会试着去对每个概念进行详尽的解释。阅读此书并不会帮助你成为专业程序员，或者挣取大量资金。但是这本书会为读者提供一些可行性的工具与想法，诸如：对交易策略的分析，执行和展示，或是其他一些相关量化主题。图1.1描述了接下来几个章节将会讨论到的主要信息。


